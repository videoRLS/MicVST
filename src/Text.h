#pragma once
#include <juce_core/juce_core.h>
#include <vector>

// Everything MicVST shows to the user - window texts, menus, dialogs, tooltips and the log file -
// is written in Turkish in the sources and shown in the language chosen at the bottom of the window
// (Türkçe by default; English, 中文, हिन्दी, Español, Français, العربية, Português, Русский, Deutsch,
// 日本語). The rules:
//
//  * Never build user-facing text with juce::String (const char*): JUCE reads such literals as
//    Latin-1, so every UTF-8 letter (ç, ğ, ı, ö, ş, ü) turns into two garbage characters. Use
//    tr ("...") instead; the sources are UTF-8 (/utf-8 for MSVC).
//  * tr() looks the Turkish text up in the current language's table (src/i18n/Translations.cpp,
//    generated by tools/i18n.py from i18n/<language>.json; every Turkish text of the sources is a key
//    there - a unit test checks that every language has every key). Texts that are stored in Turkish
//    and translated where they are shown (effect and parameter names, preset and theme names) are
//    marked TRK ("...") so the tool finds them; show them with tr (juce::String).
//  * Decimal numbers use the language's decimal mark ("49,7 ms" in Turkish, "49.7 ms" in English),
//    percentages its order ("%45" in Turkish, "45%" in most others).
#define TRK(text) text

namespace micvst
{
    struct Language
    {
        const char* id;          // "tr", "en", ... (stored in config.xml)
        const char* nativeName;  // shown in the language list, in its own script
        bool decimalComma;       // 3,5 instead of 3.5
        bool percentFirst;       // %45 instead of 45%
    };
    const std::vector<Language>& languages();

    // Message thread (at start, before any window; and when the user picks another language).
    // Unknown id: Türkçe. Also installs JUCE's own texts (dialog buttons, the text field menu).
    void setLanguage (const juce::String& id);
    juce::String currentLanguage();

    juce::String tr (const char* utf8TurkishText);
    juce::String tr (const juce::String& turkishText);   // stored Turkish keys (TRK) at display time

    // Number with a fixed count of decimals in the language's notation.
    juce::String trNumber (double value, int decimals);
    // "%45" / "45%".
    juce::String trPercent (double percent);

    // Turkish text for a stored scan-skip reason. plugin_cache.xml keeps the English key words
    // ("unresponsive", "failed (exit 0x...)", ...) - also those written by older versions.
    juce::String scanSkipReasonText (const juce::String& reason);

    // Kept for the callers of 1.2.1/1.2.2: installs the current language's texts for JUCE's own
    // strings (setLanguage does it as well).
    void installTurkishTranslations();

    // A device error from JUCE for the log: the two messages JUCE does not pass through TRANS
    // ("No such device: ...", "Can't open the audio device! ...") in the user's language; the others
    // are already translated by the table installed by setLanguage.
    juce::String deviceErrorText (const juce::String& error);

    // The translation tables (src/i18n/Translations.cpp): for a language id, pairs of
    // { Turkish key, translation } ending with { nullptr, nullptr }; nullptr for "tr" or unknown ids.
    struct TranslationPair { const char* key; const char* text; };
    const TranslationPair* translationTable (const char* languageId);
    // Every key the sources use (tools/i18n.py), ending with nullptr - for the unit test.
    const char* const* translationKeys();
}
